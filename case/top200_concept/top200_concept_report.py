def calc_top200(stock_list, start_date, end_date):
    """计算近2周涨幅TOP200"""
    # 获取2周前全市场日线
    print(f"获取 {start_date} 全市场日线...")
    df_start = pro.daily(trade_date=start_date)
    time.sleep(0.15)
    
    if len(df_start) == 0:
        print(f"警告：{start_date} 无日线数据")
        return []
    
    # 获取最新交易日全市场日线
    print(f"获取 {end_date} 全市场日线...")
    df_end = pro.daily(trade_date=end_date)
    time.sleep(0.15)
    
    if len(df_end) == 0:
        print(f"警告：{end_date} 无日线数据")
        return []
    
    # 合并计算涨幅
    df_start = df_start[['ts_code', 'close']].rename(columns={'close': 'start_price'})
    df_end = df_end[['ts_code', 'close', 'pct_chg']].rename(columns={'close': 'end_price'})
    
    merged = df_end.merge(df_start, on='ts_code', how='inner')
    
    # 排除ST（但保留用于后续分类）
    # 计算涨幅
    merged['chg'] = ((merged['end_price'] - merged['start_price']) / merged['start_price'] * 100).round(2)
    
    # 合并股票名称
    stock_names = stock_list.set_index('ts_code')['name'].to_dict()
    merged['name'] = merged['ts_code'].map(stock_names)
    
    # 排序取TOP200
    merged = merged.sort_values('chg', ascending=False).head(200)
    
    print(f"TOP200 涨幅范围: {merged.iloc[0]['chg']:.2f}% ~ {merged.iloc[-1]['chg']:.2f}%")
    
    # 构建结果
    results = []
    for _, row in merged.iterrows():
        code6 = row['ts_code'].split('.')[0]
        name = row['name'] if pd.notna(row['name']) else code6
        category = classify_stock(code6, name)
        results.append({
            'code': code6,
            'name': name,
            'ts_code': row['ts_code'],
            'start_price': row['start_price'],
            'end_price': row['end_price'],
            'chg': row['chg'],
            'start_date': start_date,
            'end_date': end_date,
            'category': category,
        })
    
    return results


def generate_report(data):
    """生成Markdown报告"""
    if not data:
        return "无数据"
    
    start_date_display = f"{data[0]['start_date'][:4]}-{data[0]['start_date'][4:6]}-{data[0]['start_date'][6:]}"
    end_date_display = f"{data[0]['end_date'][:4]}-{data[0]['end_date'][4:6]}-{data[0]['end_date'][6:]}"
    
    # 按类别汇总
    cat_data = defaultdict(list)
    for d in data:
        cat_data[d['category']].append(d)
    
    # 计算评分（涨幅之和）
    cat_scores = {}
    for cat, stocks in cat_data.items():
        total_score = sum(s['chg'] for s in stocks)
        avg_chg = total_score / len(stocks)
        cat_scores[cat] = {
            'total_score': round(total_score, 2),
            'count': len(stocks),
            'avg_chg': round(avg_chg, 2),
            'stocks': sorted(stocks, key=lambda x: x['chg'], reverse=True),
        }
    
    # 按评分排序
    sorted_cats = sorted(cat_scores.items(), key=lambda x: x[1]['total_score'], reverse=True)
    
    # 构建报告
    lines = []
    lines.append("# TOP200近2周概念汇总\n")
    lines.append(f"**数据区间**：{start_date_display} ~ {end_date_display}")
    lines.append(f"**数据来源**：tushare（真实收盘价计算）")
    lines.append(f"**评分公式**：综合评分 = 该类别所有股票涨幅之和（%）\n")
    
    # 产品类别评分排名
    lines.append("## 产品类别评分排名\n")
    lines.append("| 排名 | 产品类别 | 综合评分(%) | 同类数量 | 平均涨幅(%) | 涨幅前5股票 | 其他股票 |")
    lines.append("|:---:|:---|---:|:---:|:---:|:---|:---|")
    
    for rank, (cat, info) in enumerate(sorted_cats, 1):
        stocks = info['stocks']
        top5 = stocks[:5]
        others = stocks[5:]
        
        top5_str = "、".join(f"{s['name']}(+{s['chg']}%)" for s in top5)
        others_str = "、".join(f"{s['name']}(+{s['chg']}%)" if s['chg'] > 0 else f"{s['name']}({s['chg']}%)" for s in others)
        
        lines.append(f"| {rank} | {cat} | {info['total_score']} | {info['count']} | {info['avg_chg']} | {top5_str} | {others_str if others_str else '-'} |")
    
    # 涨幅TOP20明细
    lines.append("\n## 涨幅TOP20明细\n")
    lines.append("| 排名 | 股票代码 | 股票名称 | 涨幅(%) | 产品类别 |")
    lines.append("|:---:|:---|:---|---:|:---|")
    
    all_sorted = sorted(data, key=lambda x: x['chg'], reverse=True)
    for rank, s in enumerate(all_sorted[:20], 1):
        chg_str = f"+{s['chg']}" if s['chg'] > 0 else f"{s['chg']}"
        lines.append(f"| {rank} | {s['code']} | {s['name']} | {chg_str}% | {s['category']} |")
    
    lines.append("\n---")
    lines.append("*数据分析学习材料，不构成投资建议*")
    
    return "\n".join(lines)


