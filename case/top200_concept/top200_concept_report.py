def get_trade_dates():
    """获取最近有数据的交易日和2周前交易日"""
    # 从今天往前找最近有日线数据的交易日
    today = datetime.now().strftime('%Y%m%d')
    end_date = None
    for offset in range(10):
        d = (datetime.now() - timedelta(days=offset)).strftime('%Y%m%d')
        try:
            df = pro.daily(trade_date=d)
            time.sleep(0.15)
            if len(df) > 0:
                end_date = d
                print(f"最新有数据交易日: {end_date} ({len(df)}只)")
                break
        except:
            time.sleep(0.15)
            continue
    
    if not end_date:
        print("无法找到有数据的交易日")
        return None, None
    
    # 获取2周前的交易日（end_date往前约10个交易日）
    lookback_start = (datetime.strptime(end_date, '%Y%m%d') - timedelta(days=25)).strftime('%Y%m%d')
    cal_df = pro.trade_cal(exchange='SSE', is_open=1,
                           start_date=lookback_start,
                           end_date=end_date)
    time.sleep(0.15)
    cal_df = cal_df.sort_values('cal_date', ascending=True)
    
    if len(cal_df) < 10:
        print(f"交易日不足，仅{len(cal_df)}天")
        return None, None
    
    # 取第一个交易日作为起始日（约2周前）
    start_date = str(cal_df.iloc[0]['cal_date'])
    
    return start_date, str(end_date)


