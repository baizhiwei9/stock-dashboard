def _code_prefix(code):
    if code.startswith('6'):
        return f'sh{code}'
    elif code.startswith('0') or code.startswith('3'):
        return f'sz{code}'
    elif code.startswith('1') or code.startswith('5'):
        return f'sh{code}'
    return f'sz{code}'


def _ts_code(code):
    """6 位代码 -> tushare 格式（600519 -> 600519.SH）。"""
    return f"{code}.{'SH' if _code_prefix(code).startswith('sh') else 'SZ'}"


def fetch_stock_kline(code, days=40):
    """DataHub 股票模块个股前复权日线收盘序列（升序）。"""
    import sys
    hub = '/home/work/dumate/5eaa88f7d2d5403f9ae855f5fcfd7f34/workspace/projects/datahub-three-tier'
    deps = '/home/work/dumate/5eaa88f7d2d5403f9ae855f5fcfd7f34/workspace/py_deps'
    for path in (deps, hub):
        if path not in sys.path:
            sys.path.insert(0, path)
    start = (datetime.now() - timedelta(days=days + 30)).strftime('%Y%m%d')
    end = datetime.now().strftime('%Y%m%d')
    try:
        from data_hub.collectors.stocks import get_stock_daily
        df = get_stock_daily(_ts_code(code), start_date=start, end_date=end)
        if df is None or len(df) == 0 or 'close' not in df.columns:
            return []
        dcol = 'trade_date' if 'trade_date' in df.columns else 'date'
        return [float(x) for x in df.sort_values(dcol)['close'].tolist()]
    except Exception as e:
        print(f'  fetch_stock_kline({code}) dataHub error: {e}')
        return []


def get_top_stocks_for_etf(etf_code, top_n=3):
    pool = ETF_STOCK_POOL.get(etf_code)
    if pool is None:
        return []
    results = []
    for code in pool['stocks']:
        closes = fetch_stock_kline(code, days=40)
        if len(closes) >= 21:
            mom_20 = closes[-1] / closes[-21] - 1
            mom_5 = closes[-1] / closes[-6] - 1 if len(closes) >= 6 else 0
            if np.isfinite(mom_20):
                results.append({
                    'code': code,
                    'name': STOCK_NAMES.get(code, code),
                    'close': closes[-1],
                    'mom_20': mom_20,
                    'mom_5': mom_5,
                })
        time.sleep(0.05)
    results.sort(key=lambda x: -x['mom_20'])
    return results[:top_n]
