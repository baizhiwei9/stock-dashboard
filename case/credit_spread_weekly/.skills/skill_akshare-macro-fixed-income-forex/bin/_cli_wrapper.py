#!/usr/bin/env python3
"""
_cli_wrapper.py — coze claw env-injection wrapper for Sealed CLI Contract.

coze claw only injects managed secrets (e.g. DATA_PROVIDER_API_KEY) into
the Python execution context. Go CLI binaries executed directly cannot see
these env vars. This wrapper bridges the gap:

  python3 ./bin/_cli_wrapper.py list
  python3 ./bin/_cli_wrapper.py schema search
  python3 ./bin/_cli_wrapper.py call search --param query=test

It discovers the companion CLI binary (same directory, no .py extension,
ELF/Mach-O executable), forwards all argv + env, and propagates
stdout/stderr/exit code transparently.

DO NOT MODIFY this file. It is generated by the data-skill-creator SOP
and must remain identical across all data-skill packages.
"""

import os
import sys
import stat
import subprocess


def find_cli_binary(wrapper_dir):
    """Find the CLI binary in the same directory as this wrapper."""
    for name in os.listdir(wrapper_dir):
        path = os.path.join(wrapper_dir, name)
        if name.startswith(".") or name.startswith("_") or name.endswith(".py"):
            continue
        if os.path.isfile(path) and os.stat(path).st_mode & stat.S_IXUSR:
            return path
    return None


def main():
    wrapper_dir = os.path.dirname(os.path.abspath(__file__))
    cli_bin = find_cli_binary(wrapper_dir)
    if cli_bin is None:
        print("ERROR: no CLI binary found in", wrapper_dir, file=sys.stderr)
        sys.exit(1)

    result = subprocess.run(
        [cli_bin] + sys.argv[1:],
        env=os.environ,
        stdout=sys.stdout,
        stderr=sys.stderr,
    )
    sys.exit(result.returncode)


if __name__ == "__main__":
    main()
